"""Copy the exact WeKit lens and miuix dual-light shader strings into Java constants.

Only reads reference source; never imports or executes a reference artifact.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re


def java_strings(expression, limit=None):
    values = []
    index = 0
    while index < len(expression):
        if expression[index] != '"':
            index += 1
            continue
        start = index
        index += 1
        while index < len(expression):
            if expression[index] == "\\":
                index += 2
            elif expression[index] == '"':
                index += 1
                values.append(json.loads(expression[start:index]))
                if limit is not None and len(values) >= limit:
                    return values
                break
            else:
                index += 1
        else:
            raise ValueError("Unterminated reference string")
    return values


def constant(name, value):
    lines = value.splitlines(keepends=True)
    body = "\n".join("            " + ("" if i == 0 else "+ ") + json.dumps(line, ensure_ascii=True)
                     for i, line in enumerate(lines))
    return "    static final String " + name + " =\n" + body + ";\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--lens", type=Path, required=True)
    parser.add_argument("--miuix", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    lens = args.lens.read_text(encoding="utf-8")
    miuix = args.miuix.read_text(encoding="utf-8")
    raw = dict(re.findall(r'private const val ([A-Z_]+) = """(.*?)"""', lens, re.S))
    sdf = raw["ROUNDED_RECT_SDF"]
    plain = raw["ROUNDED_RECT_REFRACTION_SHADER"].replace("$ROUNDED_RECT_SDF", sdf)
    dispersion = raw["ROUNDED_RECT_REFRACTION_WITH_DISPERSION_SHADER"].replace("$ROUNDED_RECT_SDF", sdf)
    block = miuix.split("String buildBloomStrokeShader(boolean dualPeak)", 1)[1].split("public static final String getBLOOM", 1)[0]
    lights = java_strings(block.split("str2 = ", 1)[1], limit=1)[0]
    pieces = java_strings(block.split("return ", 1)[1])
    if len(pieces) != 3 or "lightBlock" not in block or "axisUniforms" not in block:
        raise ValueError("Unexpected bloom shader builder shape")
    bloom = pieces[0] + pieces[1] + lights + pieces[2]
    colors = java_strings(miuix.split("String COLOR_CONTROLS_SHADER = ", 1)[1], limit=1)[0]
    unpremul = java_strings(miuix.split("String UNPREMUL_SHADER = ", 1)[1], limit=1)[0]
    values = {"LENS": plain, "LENS_DISPERSION": dispersion, "BLOOM_DUAL": bloom,
              "COLOR_CONTROLS": colors, "UNPREMULTIPLY": unpremul}
    output = "// Copyright 2026 compose-miuix-ui contributors. SPDX-License-Identifier: Apache-2.0\n"
    output += "// Lens: Kyant0/AndroidLiquidGlass, via WeKit / InstallerX-Revived.\n"
    output += "// Bloom/color controls: miuix-blur-android 0.9.4-rc01. See THIRD-PARTY-NOTICES.md.\n"
    output += "// Generated by scripts/import_glass_shaders.py; reference SHA-256 is recorded per constant.\n"
    output += "package wex.ui.core.feature;\n\nfinal class LiquidGlassShaders {\n"
    output += "    private LiquidGlassShaders() { }\n\n"
    for name, value in values.items():
        digest = hashlib.sha256(value.encode("utf-8")).hexdigest()
        output += "    // " + name + " SHA-256: " + digest + "\n" + constant(name, value) + "\n"
        print(name, len(value), digest)
    output += "}\n"
    with args.output.open("x", encoding="utf-8", newline="\n") as stream:
        stream.write(output)


if __name__ == "__main__":
    main()
