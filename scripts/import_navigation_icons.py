"""Translate WeKit's Material Symbols path commands to Android Path without executing input."""
import argparse
import hashlib
from pathlib import Path
import re


ARITY = {"moveTo": 2, "lineTo": 2, "horizontalLineTo": 1, "verticalLineTo": 1,
         "quadTo": 4, "reflectiveQuadTo": 2, "close": 0}


def translate(source):
    marker = "PathBuilder $this$PathData_u24lambda_u240$iv$iv = new PathBuilder();"
    if source.count(marker) != 1 or "960.0f, 960.0f" not in source:
        raise ValueError("Unexpected reference vector structure")
    block = source.split(marker, 1)[1].split("ImageVector.Builder.addPath", 1)[0]
    x = y = start_x = start_y = qx = qy = 0.0
    previous = ""
    result = []
    for line in block.splitlines():
        line = line.strip()
        if not line:
            continue
        match = re.fullmatch(r"\$this\$PathData_u24lambda_u240\$iv\$iv\.([A-Za-z]+)\(([^)]*)\);", line)
        if match is None:
            raise ValueError("Unexpected path command: " + line)
        method, arguments = match.groups()
        relative = method.endswith("Relative")
        method = method.removesuffix("Relative")
        values = [float(value.strip().removesuffix("f")) for value in arguments.split(",") if value.strip()]
        if method not in ARITY or len(values) != ARITY[method]:
            raise ValueError((method, arguments))
        if method in ("moveTo", "lineTo"):
            nx, ny = values
            if relative:
                nx += x
                ny += y
            x, y = nx, ny
            if method == "moveTo":
                start_x, start_y = x, y
            result.append((method, [x, y]))
        elif method == "horizontalLineTo":
            x = x + values[0] if relative else values[0]
            result.append(("lineTo", [x, y]))
        elif method == "verticalLineTo":
            y = y + values[0] if relative else values[0]
            result.append(("lineTo", [x, y]))
        elif method == "quadTo":
            cx, cy, nx, ny = values
            if relative:
                cx += x; cy += y; nx += x; ny += y
            qx, qy, x, y = cx, cy, nx, ny
            result.append(("quadTo", [cx, cy, nx, ny]))
        elif method == "reflectiveQuadTo":
            cx, cy = (2 * x - qx, 2 * y - qy) if previous in ("quadTo", "reflectiveQuadTo") else (x, y)
            nx, ny = values
            if relative:
                nx += x; ny += y
            qx, qy, x, y = cx, cy, nx, ny
            result.append(("quadTo", [cx, cy, nx, ny]))
        else:
            x, y = start_x, start_y
            result.append(("close", []))
        previous = method
    if not result or any(abs(v) > 1000 for _, values in result for v in values):
        raise ValueError("Invalid vector coordinates")
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--reference", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    output = ["// Google Material Symbols, Apache-2.0. Geometry from WeKit's composables 2.2.1 dependency.",
              "// Generated by scripts/import_navigation_icons.py. See THIRD-PARTY-NOTICES.md.",
              "package wex.ui.core.feature;", "", "import android.graphics.Path;", "",
              "final class NavigationIcons {", "    private NavigationIcons() { }",
              "    static Path create(int index, boolean filled) {", "        switch (index) {"]
    names = ["Home", "Contacts", "Explore", "Person"]
    for index, name in enumerate(names):
        output.append(f"            case {index}: return filled ? {name.lower()}Filled() : {name.lower()}Outline();")
    output += ["            default: throw new IllegalArgumentException(\"Unknown native tab index\");", "        }", "    }", ""]
    for package, suffix in [("outlined", "Outline"), ("outlinedfilled", "Filled")]:
        for name in names:
            source = (args.reference / ("com.composables.icons.materialsymbols." + package + "." + name + "Kt.java")).read_text(encoding="utf-8")
            commands = translate(source)
            digest = hashlib.sha256(repr(commands).encode("utf-8")).hexdigest()
            output += ["    // " + name + suffix + " commands SHA-256: " + digest,
                       "    private static Path " + name.lower() + suffix + "() {", "        Path path = new Path();"]
            for method, values in commands:
                output.append("        path." + method + "(" + ", ".join(str(value) + "f" for value in values) + ");")
            output += ["        return path;", "    }", ""]
            print(name + suffix, len(commands), digest)
    output += ["}", ""]
    with args.output.open("x", encoding="utf-8", newline="\n") as stream:
        stream.write("\n".join(output))


if __name__ == "__main__":
    main()
